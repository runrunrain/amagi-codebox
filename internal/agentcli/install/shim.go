package install

import (
	"os"
	"path/filepath"
	"strings"
)

// shimPlatform 是 shim 的目标平台风格。内容生成接受该参数而非读
// runtime.GOOS，使 Windows 行为可在任意 OS 上测试（CLAUDE.md：平台差异用
// build tag 分文件选择当前值，见 platform_unix.go / platform_windows.go）。
type shimPlatform string

const (
	shimUnix    shimPlatform = "unix"    // <home>/bin/codebox-agent（POSIX sh，0755）
	shimWindows shimPlatform = "windows" // <home>/bin/codebox-agent.cmd（批处理）
)

// shimBaseName shim 主文件名（不含平台扩展名）。
const shimBaseName = "codebox-agent"

// shimSpec 生成指定平台风格的 shim 托管文件描述。
func shimSpec(home, exePath string, p shimPlatform) managedFile {
	if p == shimWindows {
		return managedFile{
			path: filepath.Join(home, "bin", shimBaseName+".cmd"),
			mode: 0o644,
			mark: func(hash string) string { return "rem amagi-codebox managed sha256:" + hash + "\r\n" },
			body: windowsShimBody(home, exePath),
		}
	}
	return managedFile{
		path: filepath.Join(home, "bin", shimBaseName),
		mode: 0o755,
		mark: func(hash string) string { return "# amagi-codebox managed sha256:" + hash + "\n" },
		body: unixShimBody(home, exePath),
	}
}

// unixShimBody 生成 POSIX sh shim：export AMAGI_CODEBOX_HOME 保证 shim 所在
// home 与 CLI 的端点发现（--home 缺省链）一致，再 exec 应用二进制的 cli
// 子命令（分发点在应用 wails.Run 之前，见 DESIGN §1）。
func unixShimBody(home, exePath string) string {
	return strings.Join([]string{
		"#!/bin/sh",
		"# codebox-agent CLI shim —— 由 Amagi CodeBox 应用生成；重新生成请使用应用设置。",
		"# 用法示例：codebox-agent status --json",
		"export AMAGI_CODEBOX_HOME=" + shellQuote(home),
		"exec " + shellQuote(exePath) + " cli \"$@\"",
		"",
	}, "\n")
}

// windowsShimBody 生成批处理 shim（CRLF）。
//
// 编码防坑（中文 Windows 用户名）：cmd.exe 默认按活动控制台代码页（简体中文为
// CP936/GBK，无控制台时按 ACP）逐行按字节偏移解析 .cmd。若把 UTF-8 编码的
// C:\Users\毛润\... 直接写进脚本字面量，CP936 下会被解码为 C:\Users\姣涙鼎\...，
// 导致 CLI 找不到 endpoint.json（exit 3）。因此：
//  1. AMAGI_CODEBOX_HOME 恒由 "%~dp0.." 在 cmd 内部按 UTF-16 WCHAR 解析，脚本零非 ASCII；
//  2. exePath 为纯 ASCII，或虽含非 ASCII 但与 home 同盘且相对路径为纯 ASCII（覆盖
//     %USERPROFILE%\.amagi-codebox 与 %LOCALAPPDATA%\Programs 等全部每用户安装形态）时，
//     改写为 "%AMAGI_CODEBOX_HOME%\<rel>"，保持整份 .cmd 100% 7-bit ASCII；
//  3. 仅当 exePath 位于跨盘/非 ASCII 子目录（如 D:\工具\amagi-codebox.exe）时，
//     在纯 ASCII 前导行保存原代码页并切到 65001，执行后恢复原代码页与退出码。
//
// % 转义为 %%（批处理文件内双引号中 % 仍会展开）；setlocal DisableDelayedExpansion 防 ! 意外展开。
func windowsShimBody(home, exePath string) string {
	target, asciiOnly := windowsExeTarget(home, exePath)
	lines := []string{
		"@echo off",
		"rem codebox-agent CLI shim - generated by Amagi CodeBox app",
		"setlocal DisableDelayedExpansion",
		"for %%I in (\"%~dp0..\") do set \"AMAGI_CODEBOX_HOME=%%~fI\"",
	}
	if asciiOnly {
		lines = append(lines,
			"\""+target+"\" cli %*",
			"exit /b %ERRORLEVEL%",
			"",
		)
		return strings.Join(lines, "\r\n")
	}
	lines = append(lines,
		"set \"_CB_CP=\"",
		"for /f \"tokens=2 delims=:\" %%C in ('chcp 2^>nul') do for /f \"tokens=1 delims=. \" %%D in (\"%%C\") do set \"_CB_CP=%%D\"",
		"if not \"%_CB_CP%\"==\"65001\" chcp 65001 >nul 2>&1",
		"\""+target+"\" cli %*",
		"set \"_CB_RC=%ERRORLEVEL%\"",
		"if defined _CB_CP if not \"%_CB_CP%\"==\"65001\" chcp %_CB_CP% >nul 2>&1",
		"exit /b %_CB_RC%",
		"",
	)
	return strings.Join(lines, "\r\n")
}

// windowsExeTarget 计算批处理调用的目标可执行路径表达式（已完成 % 转义）及整份
// shim 是否可保持纯 7-bit ASCII。纯字符串计算，不依赖宿主 OS 的 filepath 语义。
func windowsExeTarget(home, exePath string) (target string, asciiOnly bool) {
	if isASCII(exePath) {
		return batchEscape(exePath), true
	}
	if rel, ok := windowsRelPath(home, exePath); ok && isASCII(rel) {
		return "%AMAGI_CODEBOX_HOME%\\" + batchEscape(rel), true
	}
	return batchEscape(exePath), false
}

func isASCII(s string) bool {
	for i := 0; i < len(s); i++ {
		if s[i] >= 0x80 {
			return false
		}
	}
	return true
}

// windowsRelPath 纯字符串计算同盘符 Windows 绝对路径 base 到 target 的相对路径
// （以 `\` 分隔）。任一输入非 `<盘符>:\...`、跨盘符、含 `.`/`..` 段或目标为空时
// 返回 ("", false)。
func windowsRelPath(base, target string) (string, bool) {
	bDrive, bSegs, ok := parseWinDrivePath(base)
	if !ok {
		return "", false
	}
	tDrive, tSegs, ok := parseWinDrivePath(target)
	if !ok || len(tSegs) == 0 || !strings.EqualFold(bDrive, tDrive) {
		return "", false
	}
	common := 0
	for common < len(bSegs) && common < len(tSegs) && strings.EqualFold(bSegs[common], tSegs[common]) {
		common++
	}
	out := make([]string, 0, (len(bSegs)-common)+len(tSegs)-common)
	for i := common; i < len(bSegs); i++ {
		out = append(out, "..")
	}
	out = append(out, tSegs[common:]...)
	if len(out) == 0 {
		return "", false
	}
	return strings.Join(out, `\`), true
}

func parseWinDrivePath(p string) (drive string, segs []string, ok bool) {
	norm := strings.ReplaceAll(p, "/", `\`)
	if len(norm) < 3 || norm[1] != ':' || norm[2] != '\\' {
		return "", nil, false
	}
	d := norm[0]
	if (d < 'A' || d > 'Z') && (d < 'a' || d > 'z') {
		return "", nil, false
	}
	rest := strings.Trim(norm[3:], `\`)
	if rest == "" {
		return norm[:2], nil, true
	}
	parts := strings.Split(rest, `\`)
	out := make([]string, 0, len(parts))
	for _, seg := range parts {
		if seg == "" {
			continue
		}
		if seg == "." || seg == ".." {
			return "", nil, false
		}
		out = append(out, seg)
	}
	return norm[:2], out, true
}

// shellQuote POSIX sh 单引号引用：内嵌单引号转义为 '\”（路径含空格/引号安全）。
func shellQuote(v string) string {
	return "'" + strings.ReplaceAll(v, "'", `'\''`) + "'"
}

// batchEscape 批处理 % 转义。
func batchEscape(v string) string {
	return strings.ReplaceAll(v, "%", "%%")
}

// BinDir 返回 shim 目录（<home>/bin）。
func (m *Manager) BinDir() string { return filepath.Join(m.home, "bin") }

// ShimPath 返回当前平台 shim 的绝对路径。
func (m *Manager) ShimPath() string {
	return shimSpec(m.home, m.exePath, m.platform).path
}

// PathHint 返回设置页展示的 PATH 提示。
func (m *Manager) PathHint() string {
	return "将 " + m.BinDir() + " 加入 PATH，或直接使用完整路径运行 " + shimBaseName + "。"
}

// ShimStatus 查询 shim 状态。
func (m *Manager) ShimStatus() Status {
	spec := shimSpec(m.home, m.exePath, m.platform)
	if err := ensureDirPath(m.home, []string{"bin"}, false); err != nil {
		return Status{Path: spec.path, State: StateInvalid, Message: err.Error()}
	}
	return inspectManaged(spec)
}

// InstallShim 幂等安装 shim：内容一致不写盘；文件被外部改动（无有效托管
// 标记）时保留并返回 *ConflictedError。显式安装成功会清除用户清理记录。
func (m *Manager) InstallShim() error {
	if err := ensureDirPath(m.home, []string{"bin"}, true); err != nil {
		return err
	}
	if err := installManaged(shimSpec(m.home, m.exePath, m.platform)); err != nil {
		return err
	}
	return m.setDeclined(prefShim, false)
}

// RemoveShim 清理 shim（外部改动的文件保留），尽量移除空的 bin 目录，
// 并记录用户显式清理的选择（应用启动默认安装不再装回）。
func (m *Manager) RemoveShim() error {
	if err := ensureDirPath(m.home, []string{"bin"}, false); err != nil {
		return err
	}
	if err := removeManaged(shimSpec(m.home, m.exePath, m.platform)); err != nil {
		return err
	}
	_ = os.Remove(m.BinDir()) // 仅空目录可删，失败忽略
	return m.setDeclined(prefShim, true)
}
