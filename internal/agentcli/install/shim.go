package install

import (
	"os"
	"path/filepath"
	"strings"
)

// shimPlatform 是 shim 的目标平台风格。内容生成接受该参数而非读
// runtime.GOOS，使 Windows 行为可在任意 OS 上测试（CLAUDE.md：平台差异用
// build tag 分文件选择当前值，见 platform_unix.go / platform_windows.go）。
type shimPlatform string

const (
	shimUnix    shimPlatform = "unix"    // <home>/bin/codebox-agent（POSIX sh，0755）
	shimWindows shimPlatform = "windows" // <home>/bin/codebox-agent.cmd（批处理）
)

// shimBaseName shim 主文件名（不含平台扩展名）。
const shimBaseName = "codebox-agent"

// shimSpec 生成指定平台风格的 shim 托管文件描述。
func shimSpec(home, exePath string, p shimPlatform) managedFile {
	if p == shimWindows {
		return managedFile{
			path: filepath.Join(home, "bin", shimBaseName+".cmd"),
			mode: 0o644,
			mark: func(hash string) string { return "rem amagi-codebox managed sha256:" + hash + "\r\n" },
			body: windowsShimBody(home, exePath),
		}
	}
	return managedFile{
		path: filepath.Join(home, "bin", shimBaseName),
		mode: 0o755,
		mark: func(hash string) string { return "# amagi-codebox managed sha256:" + hash + "\n" },
		body: unixShimBody(home, exePath),
	}
}

// unixShimBody 生成 POSIX sh shim：export AMAGI_CODEBOX_HOME 保证 shim 所在
// home 与 CLI 的端点发现（--home 缺省链）一致，再 exec 应用二进制的 cli
// 子命令（分发点在应用 wails.Run 之前，见 DESIGN §1）。
func unixShimBody(home, exePath string) string {
	return strings.Join([]string{
		"#!/bin/sh",
		"# codebox-agent CLI shim —— 由 Amagi CodeBox 应用生成；重新生成请使用应用设置。",
		"# 用法示例：codebox-agent status --json",
		"export AMAGI_CODEBOX_HOME=" + shellQuote(home),
		"exec " + shellQuote(exePath) + " cli \"$@\"",
		"",
	}, "\n")
}

// windowsShimBody 生成批处理 shim（CRLF）。% 转义为 %%（批处理文件内
// 双引号中 % 仍会展开）；setlocal DisableDelayedExpansion 防 ! 意外展开。
func windowsShimBody(home, exePath string) string {
	return strings.Join([]string{
		"@echo off",
		"rem codebox-agent CLI shim - generated by Amagi CodeBox app",
		"setlocal DisableDelayedExpansion",
		"set \"AMAGI_CODEBOX_HOME=" + batchEscape(home) + "\"",
		"\"" + batchEscape(exePath) + "\" cli %*",
		"exit /b %ERRORLEVEL%",
		"",
	}, "\r\n")
}

// shellQuote POSIX sh 单引号引用：内嵌单引号转义为 '\”（路径含空格/引号安全）。
func shellQuote(v string) string {
	return "'" + strings.ReplaceAll(v, "'", `'\''`) + "'"
}

// batchEscape 批处理 % 转义。
func batchEscape(v string) string {
	return strings.ReplaceAll(v, "%", "%%")
}

// BinDir 返回 shim 目录（<home>/bin）。
func (m *Manager) BinDir() string { return filepath.Join(m.home, "bin") }

// ShimPath 返回当前平台 shim 的绝对路径。
func (m *Manager) ShimPath() string {
	return shimSpec(m.home, m.exePath, m.platform).path
}

// PathHint 返回设置页展示的 PATH 提示。
func (m *Manager) PathHint() string {
	return "将 " + m.BinDir() + " 加入 PATH，或直接使用完整路径运行 " + shimBaseName + "。"
}

// ShimStatus 查询 shim 状态。
func (m *Manager) ShimStatus() Status {
	spec := shimSpec(m.home, m.exePath, m.platform)
	if err := ensureDirPath(m.home, []string{"bin"}, false); err != nil {
		return Status{Path: spec.path, State: StateInvalid, Message: err.Error()}
	}
	return inspectManaged(spec)
}

// InstallShim 幂等安装 shim：内容一致不写盘；文件被外部改动（无有效托管
// 标记）时保留并返回 *ConflictedError。显式安装成功会清除用户清理记录。
func (m *Manager) InstallShim() error {
	if err := ensureDirPath(m.home, []string{"bin"}, true); err != nil {
		return err
	}
	if err := installManaged(shimSpec(m.home, m.exePath, m.platform)); err != nil {
		return err
	}
	return m.setDeclined(prefShim, false)
}

// RemoveShim 清理 shim（外部改动的文件保留），尽量移除空的 bin 目录，
// 并记录用户显式清理的选择（应用启动默认安装不再装回）。
func (m *Manager) RemoveShim() error {
	if err := ensureDirPath(m.home, []string{"bin"}, false); err != nil {
		return err
	}
	if err := removeManaged(shimSpec(m.home, m.exePath, m.platform)); err != nil {
		return err
	}
	_ = os.Remove(m.BinDir()) // 仅空目录可删，失败忽略
	return m.setDeclined(prefShim, true)
}
